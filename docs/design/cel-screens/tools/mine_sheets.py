REFS={'bg2':'bg-step1.png','miss3':'slabs.png'}
def run(name):
    out=name+'.png'
    if os.path.exists(out): return out,'skip'
    size,p=JOBS[name]; err=''
    for i in range(5):
        try:
            t=time.time(); st,d=post({'model':ARK,'prompt':p,'size':size,'response_format':'b64_json','watermark':False,'image':b64(REFS.get(name,'ref-mine.png'))})
            if st==429: time.sleep(25*(i+1)); continue
            meta={'file':out,'model':ARK,'prompt':p,'reference':'现在的矿洞那一屏','seconds':round(time.time()-t,1),'status':st,'usage':d.get('usage'),'date':time.strftime('%Y-%m-%d')}
            if st==200: open(out,'wb').write(base64.b64decode(d['data'][0]['b64_json']))
            else: meta['error']=str(d.get('error'))[:300]
            json.dump(meta,open(name+'.json','w'),ensure_ascii=False,indent=1); return out,st,meta.get('error','')
        except Exception as e: err=repr(e)[:100]; time.sleep(3)
    return out,'failed',err
if __name__=='__main__':
    with cf.ThreadPoolExecutor(2) as ex:
        for r in ex.map(run,sys.argv[1:] or list(JOBS)): print(r,flush=True)
